// Generates responsive WebP variants + blur placeholders from the source JPEGs.
//
//   node scripts/optimize-images.mjs
//
// The site is a static export with `images.unoptimized`, so next/image emits
// the src untouched — there is no server to resize on demand. That makes the
// asset pipeline our job: the source art is 1024x1024 at ~870KB apiece, and
// cards display it in a 3:2 box a few hundred pixels wide.
//
// Writes, for each source image:
//   <name>.webp        1024w, detail-page hero
//   <name>-card.webp    720w, 3:2 crop for grid cards
// plus src/data/image-placeholders.ts holding a tiny base64 LQIP per image.

import { readdirSync, writeFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, parse } from 'node:path';

import sharp from 'sharp';

// Sources live outside public/ so the 13MB of originals never ship.
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'assets', 'lounges');
// Real, freely-licensed photographs of specific lounges. See CREDITS.md.
const realDir = join(root, 'assets', 'lounges', 'real');
const dir = join(root, 'public', 'images', 'lounges');
const placeholderOut = join(root, 'src', 'data', 'image-placeholders.ts');

// The hero renders as a wide banner, so crop to 16:9 rather than the square
// the placeholder art happens to be. Never upscale past the source width.
const HERO_MAX_WIDTH = 1600;
const CARD_WIDTH = 720;
const CARD_HEIGHT = 480; // 3:2, matching the card's aspect box

const kb = (bytes) => `${(bytes / 1024).toFixed(0)}KB`;

function listJpgs(directory) {
  try {
    return readdirSync(directory)
      .filter((f) => f.endsWith('.jpg'))
      .sort()
      .map((f) => join(directory, f));
  } catch {
    return [];
  }
}

async function main() {
  // Generic placeholder art, plus real photographs of specific lounges.
  const sources = [...listJpgs(srcDir), ...listJpgs(realDir)];

  if (sources.length === 0) throw new Error(`No source .jpg files in ${srcDir}`);

  const placeholders = {};
  let before = 0;
  let after = 0;

  for (const src of sources) {
    const { name } = parse(src);
    before += statSync(src).size;

    const heroPath = join(dir, `${name}.webp`);
    const cardPath = join(dir, `${name}-card.webp`);

    // Never upscale past the source. sharp drops EXIF (incl. GPS) by default.
    const { width = HERO_MAX_WIDTH } = await sharp(src).metadata();
    const heroWidth = Math.min(HERO_MAX_WIDTH, width);
    const heroHeight = Math.round((heroWidth * 9) / 16);

    await sharp(src)
      .resize(heroWidth, heroHeight, { fit: 'cover', position: 'attention' })
      .webp({ quality: 78 })
      .toFile(heroPath);
    await sharp(src)
      .resize(CARD_WIDTH, CARD_HEIGHT, { fit: 'cover', position: 'attention' })
      .webp({ quality: 72 })
      .toFile(cardPath);

    // 16px-wide LQIP, inlined as a data URL so it costs no extra request.
    const lqip = await sharp(src).resize(16, 9, { fit: 'cover' }).webp({ quality: 40 }).toBuffer();
    placeholders[`/images/lounges/${name}.webp`] = `data:image/webp;base64,${lqip.toString('base64')}`;

    const heroSize = statSync(heroPath).size;
    const cardSize = statSync(cardPath).size;
    after += heroSize + cardSize;

    console.log(
      `${(name + '.jpg').padEnd(38)} ${kb(statSync(src).size).padStart(7)} -> hero ${kb(heroSize).padStart(6)} + card ${kb(cardSize).padStart(6)}`
    );
  }

  const entries = Object.entries(placeholders)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join('\n');

  writeFileSync(
    placeholderOut,
    `// AUTO-GENERATED by scripts/optimize-images.mjs — do not edit by hand.
// Tiny inline LQIPs, keyed by the hero image path stored on each lounge.

export const imagePlaceholders: Record<string, string> = {
${entries}
};
`
  );

  console.log(
    `\n${sources.length} images: ${kb(before)} -> ${kb(after)} (${(before / after).toFixed(1)}x smaller)`
  );
  console.log(`Wrote ${placeholderOut}`);
}

main();
